#!/usr/bin/env python3
"""lint.py — blocking CI gate on agent config.

Checks the canonical `.agents/` tree (and `stacks/` for structure) against the
constraints in work order §5. Fails (exit non-zero) on any of the 9 hard
conditions; prints a non-blocking coverage report otherwise.

Hard fail conditions (§5):
  1. Missing frontmatter / missing `trigger` / unrecognised trigger value
     (incl. case variants like `alwaysOn`, `modelDecision`).
  2. Frontmatter present in `AGENTS.md` / `GEMINI.md`.
  3. `rules/*.md` nested in subdirectories (would not load).
  4. File > 24,000 bytes; aggregate always-on > 20,000 tokens.
  5. `description` missing when `trigger: model_decision` (required).
  6. `globs` missing when `trigger: glob`.
  7. Unknown frontmatter keys.
  8. Drift: `manifest.json` `output_hash` != file on disk.
  9. A generated file hand-edited (marker missing / content changed).

Non-blocking report: per-rule tool coverage matrix, always-on token cost vs
budget, rules excluded by `tier_min` for the current tier.

`--fix` may rewrite *generated* files (those listed in the manifest) to clear
drift; it must NEVER rewrite canonical files under `.agents/`.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from dataclasses import dataclass, field
from pathlib import Path

import yaml

# --- constants -------------------------------------------------------------

KNOWN_KEYS = {"trigger", "description", "globs", "tools", "tier_min"}
VALID_TRIGGERS = {"always_on", "model_decision", "glob", "manual"}
TIER_RANK = {"small": 0, "mid": 1, "frontier": 2}
MAX_FILE_BYTES = 24_000
ALWAYS_ON_TOKEN_BUDGET = 20_000
GENERATED_MARKER = "<!-- generated by sync.py — do not edit -->"
ALL_TOOLS = ["claude", "copilot", "antigravity", "qwen", "codex"]


# --- helpers ---------------------------------------------------------------

def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def estimate_tokens(text: str) -> int:
    """Rough token estimate (~4 chars/token). Good enough for budget gating."""
    return len(text) // 4


def parse_frontmatter(text: str) -> tuple[dict | None, str]:
    """Return (frontmatter_dict_or_None, body). Frontmatter must be the first
    lines, delimited by `---`. Returns (None, text) when absent."""
    if not text.startswith("---"):
        return None, text
    lines = text.split("\n")
    if lines[0].strip() != "---":
        return None, text
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            raw = "\n".join(lines[1:i])
            try:
                data = yaml.safe_load(raw)
            except yaml.YAMLError:
                data = None
            if not isinstance(data, dict):
                data = None
            body = "\n".join(lines[i + 1:])
            return data, body
    return None, text


# --- result container ------------------------------------------------------

@dataclass
class LintResult:
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    report: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.errors


# --- core lint -------------------------------------------------------------

def _lint_rule_file(
    res: LintResult, root: Path, f: Path
) -> tuple[str, str, list[str], str | None, int] | None:
    """Run conditions 1,4,5,6,7 on one rule file (root or stack pack).

    Returns (rel, trigger, tools, tier_min, always_on_body_tokens) or None
    when the file has no frontmatter (already reported as [1])."""
    rel = f.relative_to(root).as_posix()
    text = f.read_text(encoding="utf-8")
    fm, body = parse_frontmatter(text)

    if fm is None:
        res.errors.append(f"[1] {rel}: missing frontmatter")
        return None

    # condition 7: unknown keys
    unknown = set(fm.keys()) - KNOWN_KEYS
    if unknown:
        res.errors.append(
            f"[7] {rel}: unknown frontmatter key(s): {', '.join(sorted(unknown))}"
        )

    # condition 1: trigger present + recognised
    trigger = fm.get("trigger")
    if trigger is None:
        res.errors.append(f"[1] {rel}: missing 'trigger'")
        trigger = ""
    elif trigger not in VALID_TRIGGERS:
        res.errors.append(
            f"[1] {rel}: unrecognised trigger '{trigger}' "
            f"(valid: {', '.join(sorted(VALID_TRIGGERS))})"
        )

    # condition 5: description
    if trigger == "model_decision" and not fm.get("description"):
        res.errors.append(
            f"[5] {rel}: 'description' required when trigger: model_decision"
        )
    elif not fm.get("description"):
        res.warnings.append(f"[5] {rel}: missing 'description' (warn)")

    # condition 6: globs
    if trigger == "glob" and not fm.get("globs"):
        res.errors.append(f"[6] {rel}: 'globs' required when trigger: glob")

    # condition 4: per-file size
    if len(text.encode("utf-8")) > MAX_FILE_BYTES:
        res.errors.append(
            f"[4] {rel}: {len(text.encode('utf-8'))} bytes > {MAX_FILE_BYTES} limit"
        )

    body_tokens = estimate_tokens(body) if trigger == "always_on" else 0
    tools = fm.get("tools") or ALL_TOOLS
    return (rel, str(trigger), list(tools), fm.get("tier_min"), body_tokens)


def lint(root: Path, tier: str = "mid", fix: bool = False) -> LintResult:
    res = LintResult()
    agents = root / ".agents"
    rules_dir = agents / "rules"

    # --- condition 3: nested rule files ------------------------------------
    if rules_dir.is_dir():
        for sub in sorted(rules_dir.iterdir()):
            if sub.is_dir():
                res.errors.append(
                    f"[3] nested rule directory '{sub.relative_to(root)}' — "
                    f"Antigravity only scans immediate .md children; move files up "
                    f"or register them in .agents/rules.json"
                )

    # --- per-rule checks (1,4,5,6,7) --------------------------------------
    # Root rules plus every stack pack's rules (same schema, §4.4).
    always_on_tokens = 0
    # (rel, trigger, tools, tier_min)
    rule_rows: list[tuple[str, str, list[str], str | None]] = []
    rule_files: list[Path] = []
    if rules_dir.is_dir():
        rule_files.extend(sorted(rules_dir.glob("*.md")))
    stacks_dir = root / "stacks"
    if stacks_dir.is_dir():
        for stack_dir in sorted(stacks_dir.iterdir()):
            s_rules = stack_dir / "rules"
            if s_rules.is_dir():
                rule_files.extend(sorted(s_rules.glob("*.md")))

    for f in rule_files:
        row = _lint_rule_file(res, root, f)
        if row is None:
            continue
        rel, trigger, tools, tier_min, body_tokens = row
        always_on_tokens += body_tokens
        rule_rows.append((rel, trigger, tools, tier_min))

    # condition 4: aggregate always-on budget
    if always_on_tokens > ALWAYS_ON_TOKEN_BUDGET:
        res.errors.append(
            f"[4] aggregate always-on ~{always_on_tokens} tokens > "
            f"{ALWAYS_ON_TOKEN_BUDGET} budget"
        )

    # --- condition 2: frontmatter in root entry files ----------------------
    for name in ("AGENTS.md", "GEMINI.md"):
        p = agents / name
        if p.is_file():
            fm, _ = parse_frontmatter(p.read_text(encoding="utf-8"))
            if fm is not None:
                res.errors.append(
                    f"[2] {name}: must NOT have frontmatter (plain Markdown, always active)"
                )

    # --- conditions 8 & 9: manifest drift + hand-edited generated files ----
    manifest_path = root / "sync" / "manifest.json"
    if manifest_path.is_file():
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        for source, entry in manifest.get("entries", {}).items():
            for out_rel, stored_hash in entry.get("outputs", {}).items():
                out_path = root / out_rel
                if not out_path.is_file():
                    res.errors.append(
                        f"[8] drift: manifest lists '{out_rel}' but file is missing"
                    )
                    continue
                actual = sha256(out_path.read_bytes())
                if actual != stored_hash:
                    # Distinguish hand-edit (marker gone) from plain drift.
                    content = out_path.read_text(encoding="utf-8")
                    if GENERATED_MARKER not in content:
                        res.errors.append(
                            f"[9] hand-edited generated file '{out_rel}' — "
                            f"regenerate with `python sync/sync.py`"
                        )
                    else:
                        res.errors.append(
                            f"[8] drift: '{out_rel}' hash mismatch "
                            f"(manifest {stored_hash[:12]}… vs disk {actual[:12]}…)"
                        )
                    if fix:
                        _fix_generated(root, source, out_rel, res)

    # --- non-blocking report ----------------------------------------------
    _report(res, rule_rows, always_on_tokens, tier)
    return res


def _fix_generated(root: Path, source: str, out_rel: str, res: LintResult) -> None:
    """Rewrite a generated file from its canonical source. NEVER touches
    `.agents/` — canonical files are the source of truth, not the target."""
    if out_rel.startswith(".agents/"):
        res.errors.append(
            f"[fix] refusing to rewrite canonical file '{out_rel}' (under .agents/)"
        )
        return
    src = root / source
    dst = root / out_rel
    if not src.is_file():
        res.warnings.append(f"[fix] cannot regenerate '{out_rel}': source '{source}' missing")
        return
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(GENERATED_MARKER + "\n" + src.read_text(encoding="utf-8"), encoding="utf-8")
    res.report.append(f"[fix] regenerated '{out_rel}' from '{source}'")


def _report(res: LintResult, rule_rows, always_on_tokens: int, tier: str) -> None:
    res.report.append("=== coverage report (non-blocking) ===")
    if not rule_rows:
        res.report.append("  (no rules found)")
    for rel, trigger, tools, _tier_min in rule_rows:
        res.report.append(f"  {rel}: trigger={trigger}, tools={len(tools)}/5")
    res.report.append(
        f"  always-on token cost: ~{always_on_tokens} / {ALWAYS_ON_TOKEN_BUDGET} budget"
    )
    cur = TIER_RANK.get(tier, 1)
    excluded = [r for r in rule_rows if _excluded_by_tier(r, cur)]
    if excluded:
        res.report.append(f"  rules excluded by tier_min for tier '{tier}':")
        for rel, _trigger, _tools, _tm in excluded:
            res.report.append(f"    - {rel}")
    else:
        res.report.append(f"  no rules excluded by tier '{tier}'")


def _excluded_by_tier(row, cur_rank: int) -> bool:
    """A rule is excluded when its tier_min ranks ABOVE the current tier
    (i.e. the rule needs a bigger model than the one in use)."""
    _rel, _trigger, _tools, tier_min = row
    if tier_min is None:
        return False
    return TIER_RANK.get(tier_min, 0) > cur_rank


# --- CLI -------------------------------------------------------------------

def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Agent-config lint gate")
    ap.add_argument("--root", default=".", help="repo root (default: cwd)")
    ap.add_argument("--tier", default="mid", choices=list(TIER_RANK), help="current model tier")
    ap.add_argument("--fix", action="store_true", help="rewrite drifted generated files")
    args = ap.parse_args(argv)

    res = lint(Path(args.root).resolve(), tier=args.tier, fix=args.fix)

    for w in res.warnings:
        print(f"WARN  {w}")
    for e in res.errors:
        print(f"ERROR {e}")
    for line in res.report:
        print(line)

    if res.ok:
        print("\nlint: OK")
        return 0
    print(f"\nlint: FAILED ({len(res.errors)} error(s))")
    return 1


if __name__ == "__main__":
    sys.exit(main())
