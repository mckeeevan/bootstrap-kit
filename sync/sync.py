#!/usr/bin/env python3
"""sync.py — canonical → per-tool outputs (work order §6).

Reads the canonical `.agents/` tree + `stacks/` + `profile.yaml`, and emits
per-tool instruction files **only for the tools listed in the profile**.
Updates `sync/manifest.json` (game-scheduler format, §3.2). Idempotent: a
second run with no changes produces no diff.

Translation table (§6):

| Canonical trigger   | Claude                | Copilot                 | Antigravity      | Codex            |
|---------------------|-----------------------|-------------------------|------------------|------------------|
| always_on           | CLAUDE.md section     | copilot-instructions.md | AGENTS.md section| AGENTS.md section|
| glob + globs        | paths: frontmatter    | applyTo:                | pass through     | pointer          |
| model_decision      | skill or pointer      | pointer                 | pass through     | pointer          |
| manual              | .claude/commands/     | .github/prompts/        | skill (slash)    | pointer          |
| skills/*            | copy verbatim         | skip + report           | copy verbatim    | skip + report    |
| agents/*            | .claude/agents/       | .github/agents/         | subagents        | role section     |

Generated files carry a marker so lint.py can detect hand-edits (§5.9).
`--clean` removes generated files that are no longer emitted (e.g. a tool was
dropped from the profile).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from dataclasses import dataclass, field
from pathlib import Path

import yaml

# --- constants -------------------------------------------------------------

GENERATED_MARKER = "<!-- generated by sync.py — do not edit -->"
ALL_TOOLS = ["claude", "copilot", "antigravity", "qwen", "codex"]
TIER_RANK = {"small": 0, "mid": 1, "frontier": 2}
MANIFEST_VERSION = 1

DEFAULT_PROFILE = {
    "tools": list(ALL_TOOLS),
    "model": {"name": "default", "tier": "mid", "context_budget": "128k"},
    "viewer": {"mode": "hooks", "guard": "off"},
    "stacks": ["base"],
}


# --- data model ------------------------------------------------------------

@dataclass
class Rule:
    rel: str            # repo-relative canonical path, e.g. .agents/rules/python.md
    name: str           # file stem, e.g. python
    trigger: str
    description: str
    globs: str
    tools: list[str]
    tier_min: str | None
    body: str           # markdown body (frontmatter stripped)


@dataclass
class Profile:
    tools: list[str]
    tier: str
    raw: dict


# --- helpers ---------------------------------------------------------------

def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def parse_frontmatter(text: str) -> tuple[dict | None, str]:
    """Return (frontmatter_dict_or_None, body). Mirrors lint.parse_frontmatter."""
    if not text.startswith("---"):
        return None, text
    lines = text.split("\n")
    if lines[0].strip() != "---":
        return None, text
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            raw = "\n".join(lines[1:i])
            try:
                data = yaml.safe_load(raw)
            except yaml.YAMLError:
                data = None
            if not isinstance(data, dict):
                data = None
            return data, "\n".join(lines[i + 1:])
    return None, text


def load_profile(root: Path) -> Profile:
    p = root / "profile.yaml"
    raw = {}
    if p.is_file():
        loaded = yaml.safe_load(p.read_text(encoding="utf-8"))
        if isinstance(loaded, dict):
            raw = loaded
    tools = raw.get("tools") or DEFAULT_PROFILE["tools"]
    tier = (raw.get("model") or {}).get("tier") or DEFAULT_PROFILE["model"]["tier"]
    return Profile(tools=list(tools), tier=str(tier), raw=raw)


def load_rules(root: Path) -> list[Rule]:
    rules_dir = root / ".agents" / "rules"
    out: list[Rule] = []
    if not rules_dir.is_dir():
        return out
    for f in sorted(rules_dir.glob("*.md")):
        text = f.read_text(encoding="utf-8")
        fm, body = parse_frontmatter(text)
        if fm is None:
            continue  # lint.py reports missing frontmatter; sync skips it
        out.append(Rule(
            rel=f.relative_to(root).as_posix(),
            name=f.stem,
            trigger=str(fm.get("trigger", "")),
            description=str(fm.get("description", "")),
            globs=str(fm.get("globs", "")),
            tools=list(fm.get("tools") or ALL_TOOLS),
            tier_min=fm.get("tier_min"),
            body=body.strip(),
        ))
    return out


def tier_excluded(rule: Rule, tier: str) -> bool:
    """A rule is excluded when its tier_min ranks above the current tier."""
    if rule.tier_min is None:
        return False
    return TIER_RANK.get(rule.tier_min, 0) > TIER_RANK.get(tier, 1)


def write(root: Path, rel: str, content: str) -> str:
    """Write a generated file (with marker) and return its sha256."""
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(content, encoding="utf-8")
    return sha256(p.read_bytes())


def section(title: str, body: str) -> str:
    return f"## {title}\n\n{body}\n"


# --- per-tool emitters -----------------------------------------------------

def emit_claude(root: Path, rules: list[Rule], manifest: dict, written: set[str]) -> None:
    always_on = [r for r in rules if r.trigger == "always_on"]
    globs = [r for r in rules if r.trigger == "glob"]
    manual = [r for r in rules if r.trigger == "manual"]
    model_decision = [r for r in rules if r.trigger == "model_decision"]

    # CLAUDE.md — always-on sections.
    parts = [GENERATED_MARKER, "", "# CLAUDE.md", ""]
    if always_on:
        for r in always_on:
            parts.append(section(r.name, r.body))
    else:
        parts.append("_No always-on rules._\n")
    if model_decision:
        parts.append("## On-demand\n")
        for r in model_decision:
            parts.append(f"- {r.name}: {r.description}\n")
    write(root, "CLAUDE.md", "\n".join(parts).rstrip() + "\n")
    written.add("CLAUDE.md")

    # .claude/rules/<name>.md — glob rules with paths: frontmatter.
    for r in globs:
        rel = f".claude/rules/{r.name}.md"
        content = (
            GENERATED_MARKER + "\n"
            + f"---\npaths: [{r.globs}]\n---\n\n{r.body}\n"
        )
        write(root, rel, content)
        written.add(rel)

    # .claude/commands/<name>.md — manual rules.
    for r in manual:
        rel = f".claude/commands/{r.name}.md"
        content = GENERATED_MARKER + "\n" + r.body + "\n"
        write(root, rel, content)
        written.add(rel)


def emit_copilot(root: Path, rules: list[Rule], manifest: dict, written: set[str]) -> None:
    always_on = [r for r in rules if r.trigger == "always_on"]
    globs = [r for r in rules if r.trigger == "glob"]
    manual = [r for r in rules if r.trigger == "manual"]
    model_decision = [r for r in rules if r.trigger == "model_decision"]

    # .github/copilot-instructions.md — always-on sections.
    parts = [GENERATED_MARKER, "", "# Copilot instructions", ""]
    if always_on:
        for r in always_on:
            parts.append(section(r.name, r.body))
    else:
        parts.append("_No always-on rules._\n")
    if model_decision:
        parts.append("## On-demand\n")
        for r in model_decision:
            parts.append(f"- {r.name}: {r.description}\n")
    write(root, ".github/copilot-instructions.md", "\n".join(parts).rstrip() + "\n")
    written.add(".github/copilot-instructions.md")

    # .github/instructions/<name>.instructions.md — glob rules with applyTo.
    for r in globs:
        rel = f".github/instructions/{r.name}.instructions.md"
        content = (
            GENERATED_MARKER + "\n"
            + f"---\napplyTo: {r.globs}\n---\n\n{r.body}\n"
        )
        write(root, rel, content)
        written.add(rel)

    # .github/prompts/<name>.prompt.md — manual rules.
    for r in manual:
        rel = f".github/prompts/{r.name}.prompt.md"
        content = GENERATED_MARKER + "\n" + r.body + "\n"
        write(root, rel, content)
        written.add(rel)


def _agents_md_content(rules: list[Rule]) -> str:
    """AGENTS.md body — always-on sections + glob/model_decision pass-through."""
    always_on = [r for r in rules if r.trigger == "always_on"]
    globs = [r for r in rules if r.trigger == "glob"]
    model_decision = [r for r in rules if r.trigger == "model_decision"]
    parts = [GENERATED_MARKER, "", "# AGENTS.md", ""]
    if always_on:
        for r in always_on:
            parts.append(section(r.name, r.body))
    else:
        parts.append("_No always-on rules._\n")
    for r in globs + model_decision:
        extra = f" (globs: {r.globs})" if r.globs else ""
        parts.append(section(f"{r.name}{extra}", r.body))
    return "\n".join(parts).rstrip() + "\n"


def emit_antigravity(root: Path, rules: list[Rule], manifest: dict, written: set[str]) -> None:
    # GEMINI.md — always-on sections + glob/model_decision pass-through.
    # (AGENTS.md is written once by sync() for the union of AGENTS.md tools.)
    write(root, "GEMINI.md", _agents_md_content(rules))
    written.add("GEMINI.md")


def emit_codex(root: Path, rules: list[Rule], manifest: dict, written: set[str]) -> None:
    # Codex reads AGENTS.md, which is written once by sync() for the union of
    # AGENTS.md-reading tools. Nothing codex-specific to emit.
    pass


def emit_qwen(root: Path, rules: list[Rule], manifest: dict, written: set[str]) -> None:
    # QWEN.md — same content as AGENTS.md (Qwen Code reads AGENTS.md).
    write(root, "QWEN.md", _agents_md_content(rules))
    written.add("QWEN.md")


# --- manifest + index ------------------------------------------------------

def load_manifest(root: Path) -> dict:
    p = root / "sync" / "manifest.json"
    if p.is_file():
        return json.loads(p.read_text(encoding="utf-8"))
    return {"version": MANIFEST_VERSION, "entries": {}, "generated": []}


def write_manifest(root: Path, manifest: dict) -> None:
    p = root / "sync" / "manifest.json"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def write_rules_index(root: Path, rules: list[Rule], profile: Profile) -> None:
    index = {
        "version": MANIFEST_VERSION,
        "tier": profile.tier,
        "tools": profile.tools,
        "rules": [
            {
                "name": r.name,
                "trigger": r.trigger,
                "description": r.description,
                "globs": r.globs or None,
                "tools": r.tools,
                "tier_min": r.tier_min,
                "emitted_for": [t for t in profile.tools if t in r.tools],
            }
            for r in rules
        ],
    }
    p = root / ".agents" / "rules.json"
    p.write_text(json.dumps(index, indent=2, sort_keys=True) + "\n", encoding="utf-8")


# --- main sync -------------------------------------------------------------

def sync(root: Path, clean: bool = False) -> dict:
    profile = load_profile(root)
    rules = load_rules(root)

    # Filter by tier (rules needing a bigger model than in use are skipped).
    active = [r for r in rules if not tier_excluded(r, profile.tier)]

    # Previous manifest (for --clean: files it lists but we no longer emit).
    prev_manifest = load_manifest(root)

    manifest = {"version": MANIFEST_VERSION, "entries": {}, "generated": []}
    written: set[str] = set()

    # Per-tool emission, gated on the profile.
    emitters = {
        "claude": emit_claude,
        "copilot": emit_copilot,
        "antigravity": emit_antigravity,
        "codex": emit_codex,
        "qwen": emit_qwen,
    }
    for tool in profile.tools:
        fn = emitters.get(tool)
        if fn is None:
            continue
        # Rules this tool actually emits (intersection with rule.tools).
        tool_rules = [r for r in active if tool in r.tools]
        fn(root, tool_rules, manifest, written)

    # AGENTS.md is read by antigravity, codex, and qwen. Write it once for the
    # union of their rules so the tools don't clobber each other.
    agents_tools = [t for t in profile.tools if t in ("antigravity", "codex", "qwen")]
    if agents_tools:
        union = [r for r in active if any(t in r.tools for t in agents_tools)]
        write(root, "AGENTS.md", _agents_md_content(union))
        written.add("AGENTS.md")

    # Record per-source hashes in the manifest.
    for r in active:
        src_hash = sha256((root / r.rel).read_bytes())
        manifest["entries"][r.rel] = {"source_hash": src_hash, "outputs": {}}

    # Map written files back to their source rule for the manifest.
    for rel in written:
        _record_output(root, manifest, rel)

    manifest["generated"] = sorted(written)
    write_manifest(root, manifest)
    write_rules_index(root, active, profile)

    # Optional cleanup of stale generated files.
    if clean:
        _clean_stale(root, prev_manifest, written)

    return manifest


def _record_output(root: Path, manifest: dict, rel: str) -> None:
    """Attach a written file's hash to the source rule that produced it."""
    # A generated file's name matches a rule stem (e.g. python.md / python.*.md).
    stem = Path(rel).stem
    for src, entry in manifest["entries"].items():
        rule_stem = Path(src).stem
        if rule_stem == stem or rel.endswith(f"/{rule_stem}.md") or rel.endswith(f"/{rule_stem}."):
            entry["outputs"][rel] = sha256((root / rel).read_bytes())
            return
    # Aggregate files (CLAUDE.md, AGENTS.md, copilot-instructions.md) are not
    # tied to a single rule; record them under a synthetic source.
    manifest["entries"].setdefault("__aggregate__", {"source_hash": "", "outputs": {}})
    manifest["entries"]["__aggregate__"]["outputs"][rel] = sha256((root / rel).read_bytes())


def _clean_stale(root: Path, manifest: dict, written: set[str]) -> None:
    """Remove generated files no longer emitted (e.g. tool dropped from profile)."""
    for rel in list(manifest.get("generated", [])):
        if rel not in written:
            p = root / rel
            if p.is_file():
                p.unlink()
                print(f"clean: removed stale generated file '{rel}'")


# --- CLI -------------------------------------------------------------------

def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Canonical → per-tool sync")
    ap.add_argument("--root", default=".", help="repo root (default: cwd)")
    ap.add_argument("--clean", action="store_true",
                    help="remove generated files no longer emitted")
    args = ap.parse_args(argv)

    root = Path(args.root).resolve()
    manifest = sync(root, clean=args.clean)
    n_out = sum(len(e["outputs"]) for e in manifest["entries"].values())
    print(f"sync: {len(manifest['entries'])} source(s), {n_out} output(s), "
          f"{len(manifest['generated'])} generated file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
